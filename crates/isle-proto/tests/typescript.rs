//! Keeps `web/src/generated/proto.ts` in sync with the Rust wire types.
//!
//! Regenerate with:
//!     ISLE_UPDATE_TS=1 cargo test -p isle-proto --features ts --test typescript
#![cfg(feature = "ts")]

use isle_core::{
    BoardLayout, GameConfig, HarborKind, Phase, Resource, ResourceSet, Scenario, Terrain,
    TradeOffer,
};
use isle_proto::account::{AccountInfo, ApiError, Credentials, SessionGrant, SessionInfo};
use isle_proto::net::{
    BotLevel, ChatLine, ClientMsg, LegalActions, RoomInfo, SeatView, ServerMsg, Snapshot, Update,
};
use isle_proto::ranking::{
    Leaderboard, LeaderboardEntry, MatchSummary, PlayerProfile, RatingChange, SeatRating, Tier,
};
use isle_proto::{
    Action, BoardInfo, DevCard, Event, PlayerPublic, PlayerView, PrivateInfo, ReplayPlayer,
    ReplayRecord, RuleError, TradeResponse,
};
use ts_rs::{Config, TS};

fn render() -> String {
    let cfg = Config::new();
    let decls = [
        Resource::decl(&cfg),
        Terrain::decl(&cfg),
        HarborKind::decl(&cfg),
        ResourceSet::decl(&cfg),
        DevCard::decl(&cfg),
        BoardLayout::decl(&cfg),
        Scenario::decl(&cfg),
        GameConfig::decl(&cfg),
        Phase::decl(&cfg),
        TradeResponse::decl(&cfg),
        TradeOffer::decl(&cfg),
        Action::decl(&cfg),
        Event::decl(&cfg),
        RuleError::decl(&cfg),
        BoardInfo::decl(&cfg),
        PlayerPublic::decl(&cfg),
        PrivateInfo::decl(&cfg),
        PlayerView::decl(&cfg),
        BotLevel::decl(&cfg),
        Tier::decl(&cfg),
        SeatRating::decl(&cfg),
        RatingChange::decl(&cfg),
        SeatView::decl(&cfg),
        RoomInfo::decl(&cfg),
        LegalActions::decl(&cfg),
        Snapshot::decl(&cfg),
        Update::decl(&cfg),
        ChatLine::decl(&cfg),
        ClientMsg::decl(&cfg),
        ServerMsg::decl(&cfg),
        ReplayPlayer::decl(&cfg),
        ReplayRecord::decl(&cfg),
        Credentials::decl(&cfg),
        AccountInfo::decl(&cfg),
        SessionGrant::decl(&cfg),
        SessionInfo::decl(&cfg),
        ApiError::decl(&cfg),
        LeaderboardEntry::decl(&cfg),
        Leaderboard::decl(&cfg),
        MatchSummary::decl(&cfg),
        PlayerProfile::decl(&cfg),
    ];
    let mut out = String::from(
        "// @generated by crates/isle-proto/tests/typescript.rs - do not edit.\n\
         // Regenerate: ISLE_UPDATE_TS=1 cargo test -p isle-proto --features ts --test typescript\n\n",
    );
    for d in decls {
        out.push_str("export ");
        out.push_str(&d);
        out.push_str("\n\n");
    }
    out
}

#[test]
fn typescript_bindings_are_up_to_date() {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../web/src/generated/proto.ts"
    );
    let fresh = render();
    if std::env::var_os("ISLE_UPDATE_TS").is_some() {
        std::fs::write(path, &fresh).unwrap();
        return;
    }
    let current = std::fs::read_to_string(path).unwrap_or_default();
    assert!(
        current == fresh,
        "web/src/generated/proto.ts is stale; run: ISLE_UPDATE_TS=1 cargo test -p isle-proto --features ts --test typescript"
    );
}
